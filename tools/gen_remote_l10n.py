#!/usr/bin/env python3
"""Phase K: generates the remote-override layer from the bundled localizations.

  python tools/gen_remote_l10n.py          # (re)write the two generated files
  python tools/gen_remote_l10n.py --check  # exit 1 if they are out of date (use in CI / before a build)

Run it again after `flutter gen-l10n` whenever an .arb key is added, removed or its placeholders change.

Inputs (read-only): lib/l10n/gen/app_localizations.dart (abstract members = the bundled API), lib/l10n/app_en.arb (template).
Outputs:
  lib/core/l10n/remote/generated/remote_l10n_schema.dart        key -> placeholder names (the validation schema)
  lib/core/l10n/remote/generated/app_localizations_ar_remote.dart  AppLocalizationsArRemote: every member returns the validated
                                                                   remote text when present, otherwise the bundled Arabic.
"""
import json, re, sys, pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
ABSTRACT = ROOT / "lib/l10n/gen/app_localizations.dart"
EN_ARB = ROOT / "lib/l10n/app_en.arb"
OUT_DIR = ROOT / "lib/core/l10n/remote/generated"
SCHEMA_OUT = OUT_DIR / "remote_l10n_schema.dart"
CLASS_OUT = OUT_DIR / "app_localizations_ar_remote.dart"

PH = re.compile(r"\{([A-Za-z_][A-Za-z0-9_]*)\}")
GETTER = re.compile(r"^  String get (\w+);$")
METHOD = re.compile(r"^  String (\w+)\(([^)]*)\);$")


def members():
    out = []  # (key, [param names]) in file order
    for line in ABSTRACT.read_text(encoding="utf-8").splitlines():
        g = GETTER.match(line)
        if g:
            out.append((g.group(1), None))
            continue
        m = METHOD.match(line)
        if m:
            params = []
            for p in [x.strip() for x in m.group(2).split(",") if x.strip()]:
                t, n = p.split()
                assert t == "String", f"{m.group(1)}: parameter {n} is {t}, only String is supported"
                params.append(n)
            out.append((m.group(1), params))
    return out


def build():
    en = json.loads(EN_ARB.read_text(encoding="utf-8"))
    en_s = {k: v for k, v in en.items() if not k.startswith("@")}
    mem = members()
    keys = [k for k, _ in mem]
    assert len(keys) == len(set(keys)), "duplicate members"
    assert set(keys) == set(en_s), f"generated API and app_en.arb differ: {sorted(set(keys) ^ set(en_s))[:5]}"
    for k, params in mem:
        found = sorted(set(PH.findall(en_s[k])))
        declared = sorted(params or [])
        assert found == declared, f"{k}: English placeholders {found} != signature {declared}"
    keys_sorted = sorted(keys)
    lookup = dict(mem)

    s = ["// GENERATED by tools/gen_remote_l10n.py - do not edit by hand (re-run the tool after `flutter gen-l10n`).",
         "// dart format off",
         "// ignore_for_file: type=lint",
         "",
         "/// Every bundled text key and the placeholder names its value must contain (exactly, no more, no less).",
         "/// Remote translations are validated against this table; a key that is not here is ignored.",
         "const Map<String, List<String>> kRemoteL10nSchema = <String, List<String>>{"]
    for k in keys_sorted:
        ph = lookup[k] or []
        s.append(f"  '{k}': <String>[{', '.join(repr(p) for p in sorted(ph))}],")
    s.append("};")
    s.append("")

    c = ["// GENERATED by tools/gen_remote_l10n.py - do not edit by hand (re-run the tool after `flutter gen-l10n`).",
         "// dart format off",
         "// ignore_for_file: type=lint",
         "",
         "import '../../../../l10n/gen/app_localizations_ar.dart';",
         "import '../remote_template.dart';",
         "",
         "/// The bundled Arabic texts with validated remote overrides on top. A key without an override (or without a usable one)",
         "/// returns exactly the bundled Arabic text, so a missing, empty or rejected remote value can never blank a label.",
         "class AppLocalizationsArRemote extends AppLocalizationsAr {",
         "  AppLocalizationsArRemote(this._overrides) : super('ar');",
         "",
         "  final Map<String, String> _overrides;",
         ""]
    for k, params in mem:
        if params is None:
            c += ["  @override",
                  f"  String get {k} => _overrides['{k}'] ?? super.{k};", ""]
        else:
            args = ", ".join(f"'{p}': {p}" for p in params)
            sig = ", ".join(f"String {p}" for p in params)
            sup = ", ".join(params)
            c += ["  @override",
                  f"  String {k}({sig}) {{",
                  f"    final t = _overrides['{k}'];",
                  f"    return t == null ? super.{k}({sup}) : fillRemoteTemplate(t, <String, String>{{{args}}});",
                  "  }", ""]
    c.append("}")
    c.append("")
    return "\n".join(s), "\n".join(c), len(mem)


def main():
    schema, cls, n = build()
    if "--check" in sys.argv:
        ok = SCHEMA_OUT.exists() and CLASS_OUT.exists() and SCHEMA_OUT.read_text(encoding="utf-8") == schema \
            and CLASS_OUT.read_text(encoding="utf-8") == cls
        print(("up to date" if ok else "OUT OF DATE - run: python tools/gen_remote_l10n.py"), f"({n} keys)")
        sys.exit(0 if ok else 1)
    OUT_DIR.mkdir(parents=True, exist_ok=True)
    SCHEMA_OUT.write_text(schema, encoding="utf-8", newline="\n")
    CLASS_OUT.write_text(cls, encoding="utf-8", newline="\n")
    print(f"wrote {SCHEMA_OUT.relative_to(ROOT)} and {CLASS_OUT.relative_to(ROOT)} ({n} keys)")


if __name__ == "__main__":
    main()
